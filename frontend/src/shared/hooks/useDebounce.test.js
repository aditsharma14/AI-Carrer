import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import { renderHook, act } from '@testing-library/react';
import { useDebounce } from './useDebounce';

describe('useDebounce', () => {
  beforeEach(() => {
    vi.useFakeTimers();
  });

  afterEach(() => {
    vi.useRealTimers();
  });

  it('returns the initial value immediately', () => {
    const { result } = renderHook(() => useDebounce('a', 300));
    expect(result.current).toBe('a');
  });

  it('does not update before the delay elapses', () => {
    const { result, rerender } = renderHook(({ value }) => useDebounce(value, 300), {
      initialProps: { value: 'a' },
    });

    rerender({ value: 'ab' });
    act(() => vi.advanceTimersByTime(299));

    expect(result.current).toBe('a');
  });

  it('updates once the delay has elapsed', () => {
    const { result, rerender } = renderHook(({ value }) => useDebounce(value, 300), {
      initialProps: { value: 'a' },
    });

    rerender({ value: 'ab' });
    act(() => vi.advanceTimersByTime(300));

    expect(result.current).toBe('ab');
  });

  it('resets the timer on rapid successive changes (only the last value wins)', () => {
    const { result, rerender } = renderHook(({ value }) => useDebounce(value, 300), {
      initialProps: { value: 'a' },
    });

    rerender({ value: 'ab' });
    act(() => vi.advanceTimersByTime(150));
    rerender({ value: 'abc' });
    act(() => vi.advanceTimersByTime(150));

    // Only 150ms have passed since 'abc' was set — the earlier 'ab' timer
    // should have been cleared, not left to fire independently.
    expect(result.current).toBe('a');

    act(() => vi.advanceTimersByTime(150));
    expect(result.current).toBe('abc');
  });
});
